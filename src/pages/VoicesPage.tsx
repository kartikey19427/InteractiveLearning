import { useEffect, useState } from 'react';
import { Link } from 'react-router-dom';

interface Sample { file: string; provider: string; voice: string; description: string }

const OTHERS = [
  { name: 'ElevenLabs', note: 'Most lifelike; small free allowance, then paid.', url: 'https://elevenlabs.io/voice-library' },
  { name: 'OpenAI TTS', note: 'Good and cheap; needs an OpenAI key.', url: 'https://www.openai.fm' },
  { name: 'Google Cloud Text-to-Speech', note: 'Generous free tier; separate Cloud setup.', url: 'https://cloud.google.com/text-to-speech' },
];

// Temporary page for choosing a narration voice. Clips are pre-generated by
// backend/scripts/make_voice_samples.py; nothing plays until clicked.
export default function VoicesPage() {
  const [data, setData] = useState<{ line: string; samples: Sample[] } | null>(null);
  const [error, setError] = useState(false);

  useEffect(() => {
    fetch('/voices/manifest.json').then((r) => r.json()).then(setData).catch(() => setError(true));
  }, []);

  const playBrowser = () => {
    if (!data || !('speechSynthesis' in window)) return;
    speechSynthesis.cancel();
    speechSynthesis.speak(new SpeechSynthesisUtterance(data.line));
  };

  return (
    <main className="wrap">
      <nav className="crumbs"><Link to="/">← Back to search</Link></nav>
      <header>
        <div className="eyebrow">Choosing a narration voice</div>
        <h1>Voice samples</h1>
        <p>Every clip reads the same lesson line. Press play on the ones you want to hear.</p>
      </header>
      {error && <p className="verdict no">Couldn't load the samples.</p>}
      {data && (
        <>
          <section className="panel"><p className="intro">“{data.line}”</p></section>
          <section className="voices">
            {data.samples.map((s) => (
              <div className="panel voice-card" key={s.file}>
                <div className="phead"><span className="chip">{s.provider}</span><h2>{s.voice}</h2></div>
                <p className="note">{s.description}</p>
                <audio controls preload="none" src={s.file} />
              </div>
            ))}
            <div className="panel voice-card">
              <div className="phead"><span className="chip">Browser (current)</span><h2>System voice</h2></div>
              <p className="note">What lessons use today. Free, but quality depends on the device.</p>
              <button className="btn" type="button" onClick={playBrowser}>▶ Play</button>
            </div>
          </section>
          <section className="panel">
            <h2>Other providers</h2>
            <p className="note">These need their own API key, so listen on their demo pages:</p>
            <ul className="links">
              {OTHERS.map((o) => (
                <li key={o.name}><a href={o.url} target="_blank" rel="noreferrer">{o.name}</a>: {o.note}</li>
              ))}
            </ul>
          </section>
        </>
      )}
    </main>
  );
}
